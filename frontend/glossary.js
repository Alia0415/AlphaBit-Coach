  /* 按词条长度从长到短排序，避免短词抢在长词之前匹配 */
  let SORTED = [];
  let RE = null;

  /*
   * 中文术语需要在连续中文句子中命中；英文缩写则保留字母数字边界，
   * 避免把 AlphaOS 中的 Alpha 当作独立术语。
   */
  function rebuildMatcher() {
    SORTED = GLOSSARY.slice().sort((a, b) => b.term.length - a.term.length);
    const patterns = SORTED.map((g) => {
      const escaped = g.term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const startsWithAscii = /^[A-Za-z0-9_]/.test(g.term);
      const endsWithAscii = /[A-Za-z0-9_]$/.test(g.term);
      return `${startsWithAscii ? "(?<![A-Za-z0-9_])" : ""}${escaped}` +
        `${endsWithAscii ? "(?![A-Za-z0-9_])" : ""}`;
    });
    RE = new RegExp(`(${patterns.join("|")})`, "giu");
  }
  rebuildMatcher();

  /**
   * 查词条对象（用原始未转译的词条名查找）
   */
  function lookup(term) {
    return SORTED.find((g) => g.term.toLowerCase() === term.toLowerCase());
  }

  function getTerms() {
    return SORTED.map((item) => ({ ...item }));
  }

  function registerTerms(items) {
    if (!Array.isArray(items)) return 0;
    let added = 0;
    for (const item of items.slice(0, 30)) {
      const term = String(item?.term || "").trim();
      const explanation = String(item?.explanation || "").trim();
      if (term.length < 2 || term.length > 32 || explanation.length < 12 ||
          explanation.length > 300 ||
          !/^[\u3400-\u9fffA-Za-z0-9α-ωΑ-Ω%+./()（）·\-\s]+$/u.test(term) ||
          lookup(term)) continue;
      GLOSSARY.push({
        term,
        explanation,
        category: String(item?.category || "报告术语").slice(0, 20),
        color: "var(--cyan)",
        dynamic: true,
      });
      added += 1;
    }
    if (added) rebuildMatcher();
    return added;
  }

  /**
   * highlightTerms(text) → 高亮后的 HTML 字符串
   *
   * 将纯文本中的词汇替换为带颜色 + data-explanation 的 <span>
   */
  function highlightTerms(text) {
    const safe = String(text)
      .replaceAll("&", "&amp;")
      .replaceAll("<", "&lt;")
      .replaceAll(">", "&gt;")
      .replaceAll('"', "&quot;")
      .replaceAll("'", "&#039;");

    return safe.replace(RE, (match, term) => {
      const entry = lookup(term);
      if (!entry) return match;
      return `<span class="glossary-term" role="button" tabindex="0"` +
        ` data-term="${term}" style="color:${entry.color}"` +
        ` data-explanation="${entry.explanation
          .replaceAll("&", "&amp;")
          .replaceAll('"', "&quot;")}">${term}</span>` +
        "";
    });
  }

  /**
   * highlightInDOM(root) → undefined
   *
   * 遍历 DOM 树中的所有文本节点，将其文本用高亮 HTML 替换。
   * 只处理 visible 文本节点。
   */
  function highlightInDOM(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null, false);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);

    for (const node of nodes) {
      // 跳过已有高亮标记（避免重复处理）
      if (node.parentElement && node.parentElement.closest(".glossary-term")) continue;

      const html = highlightTerms(node.textContent);
      if (html === node.textContent) continue; // 没有命中任何词

      const span = document.createElement("span");
      span.innerHTML = html;
      node.parentNode.replaceChild(span, node);
    }
  }

  /* ---- 知识库持久化（localStorage） ---- */
  const KNOWLEDGE_KEY = "alphaos.glossary.knowledge";

  function getKnowledge() {
    try {
      return JSON.parse(localStorage.getItem(KNOWLEDGE_KEY)) || [];
    } catch { return []; }
  }

  function saveKnowledge(list) {
    try { localStorage.setItem(KNOWLEDGE_KEY, JSON.stringify(list)); } catch { /* noop */ }
  }

  function addKnowledge(term, color, explanation) {
    const list = getKnowledge();
    if (list.some((item) => item.term === term)) return false;
    list.push({ term, color, explanation, savedAt: Date.now() });
    saveKnowledge(list);
    return true;
  }

  function removeKnowledge(term) {
    saveKnowledge(getKnowledge().filter((item) => item.term !== term));
  }

  function isKnowledgeSaved(term) {
    return getKnowledge().some((item) => item.term === term);
  }

  /* 导出到全局 */
  const AlphaGlossary = {
    highlightTerms,
    highlightInDOM,
    lookup,
    getTerms,
    registerTerms,
    getKnowledge,
    addKnowledge,
    removeKnowledge,
    isKnowledgeSaved,
  };
